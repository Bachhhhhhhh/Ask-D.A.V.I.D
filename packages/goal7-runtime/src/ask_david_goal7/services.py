_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_FORBIDDEN_SQL = re.compile(
    r"(?i)\b(?:alter|create|delete|drop|grant|insert|merge|truncate|update|use|"
    r"with\s+credentials)\b"
)


class DorisExecutor(Protocol):
    def execute(self, sql: str) -> Iterable[Mapping[str, Any]]:
        """Execute only SQL generated by QueryService."""


class AnalyticsExecutor(Protocol):
    def read_metric_rows(self, metric_name: str) -> Iterable[Mapping[str, Any]]:
        """Read the one approved analytics input through Databricks."""


class VectorIndex(Protocol):
    def upsert(self, chunks: Sequence[ChunkRecord]) -> None:
        """Upsert derived chunks into the controlled vector index."""

    def search(
        self,
        vector: Sequence[float],
        top_k: int,
        allowed_roles: frozenset[str],
    ) -> Iterable[tuple[ChunkRecord, float]]:
        """Search vectors after the service has applied the role filter."""


class OpenSearchDataPlaneClient(Protocol):
    """Minimal injected client surface; credentials stay outside this package."""

    def bulk(self, *, body: list[dict[str, Any]]) -> Mapping[str, Any]:
        """Execute one bounded bulk request."""

    def search(self, *, index: str, body: Mapping[str, Any]) -> Mapping[str, Any]:
        """Execute one vector search request."""


@dataclass(slots=True)
class QueryService:
    """SELECT-only, allowlisted Doris boundary."""

    executor: DorisExecutor
    table_allowlist: frozenset[str] = frozenset({APPROVED_DORIS_TABLE})

    def query_metric(self, request: MetricQueryRequest) -> MetricQueryResponse:
        if request.table_name not in self.table_allowlist:
            return self._denied(request, "table is not in the approved Doris allowlist")
        if request.metric_name != APPROVED_ANALYTICS_METRIC:
            return self._denied(request, "metric is not in the approved Doris allowlist")
        if not 1 <= request.max_rows <= 100:
            return self._denied(request, "max_rows must be between 1 and 100")
        sql = self._build_metric_sql(request)
        if _FORBIDDEN_SQL.search(sql) or not re.match(r"(?is)^\s*select\b", sql):
            return self._denied(request, "generated query failed the SELECT-only guard")
        query_id = str(uuid.uuid4())
        rows = tuple(dict(row) for row in self.executor.execute(sql))[: request.max_rows]
        provenance = Provenance(
            source_system="apache-doris-serving",
            source_reference=request.table_name,
            query_id=query_id,
        )
        return MetricQueryResponse(
            status="success",
            columns=("metric_date", "category", "event_count", "metric_total"),
            rows=rows,
            provenance=provenance,
            sql=sql,
        )

    @staticmethod
    def _build_metric_sql(request: MetricQueryRequest) -> str:
        return (
            "SELECT metric_date, category, event_count, metric_total "
            f"FROM {request.table_name} "
            f"WHERE source_table = '{APPROVED_DORIS_SOURCE_TABLE}' "
            "ORDER BY metric_date ASC, category ASC "
            f"LIMIT {request.max_rows}"
        )

    @staticmethod
    def _denied(request: MetricQueryRequest, error: str) -> MetricQueryResponse:
        return MetricQueryResponse(
            status="denied",
            columns=(),
            rows=(),
            provenance=Provenance("apache-doris-serving", request.table_name, "denied"),
            sql="",
            error=error,
        )


@dataclass(slots=True)
class RetrievalService:
    """Model-checked, role-filtered OpenSearch vector boundary."""

    index: VectorIndex
    embedding_provider: EmbeddingProvider

    def retrieve(self, request: RetrievalRequest) -> RetrievalResponse:
        if not request.query.strip():
            return self._denied(request, "query must not be empty")
        if not 1 <= request.top_k <= 10:
            return self._denied(request, "top_k must be between 1 and 10")
        roles = frozenset(role.strip() for role in request.allowed_roles if role.strip())
        if not roles:
            return self._denied(request, "at least one allowed role is required")
        vector = self.embedding_provider.embed(request.query)
        self.embedding_provider.config.validate(vector)
        query_id = str(uuid.uuid4())
        provenance = Provenance("opensearch-serverless", "goal7-vector-index", query_id)
        results = tuple(
            RetrievedChunk(
                chunk_id=chunk.chunk_id,
                document_id=chunk.document_id,
                title=chunk.title,
                content=chunk.content,
                source_uri=chunk.source_uri,
                score=score,
                provenance=Provenance("s3-derived-document", chunk.source_uri, query_id),
            )
            for chunk, score in self.index.search(vector, request.top_k, roles)
        )
        return RetrievalResponse("success", request.query, results, provenance)

    @staticmethod
    def _denied(request: RetrievalRequest, error: str) -> RetrievalResponse:
        return RetrievalResponse(
            "denied",
            request.query,
            (),
            Provenance("opensearch-serverless", "goal7-vector-index", "denied"),
            error,
        )


@dataclass(slots=True)
class IndexingService:
    """Controlled deterministic chunk upsert boundary for the AOSS index."""

    index: VectorIndex

    def upsert_chunks(self, chunks: Sequence[ChunkRecord]) -> None:
        if not chunks:
            raise ValueError("at least one chunk is required")
        self.index.upsert(chunks)


@dataclass(slots=True)
class OpenSearchVectorIndex:
    """OpenSearch data-plane adapter used only by the controlled service.

    The caller injects a SigV4-authenticated client created by the deployment
    boundary. No AWS credentials or endpoint discovery is available to agents.
    """

    client: OpenSearchDataPlaneClient
    index_name: str
    embedding_provider: EmbeddingProvider

    def upsert(self, chunks: Sequence[ChunkRecord]) -> None:
        body: list[dict[str, Any]] = []
        for chunk in chunks:
            if chunk.embedding_model_id != self.embedding_provider.config.model_id:
                raise ValueError("embedding model mismatch")
            self.embedding_provider.config.validate(chunk.embedding)
            body.extend(
                [
                    {"update": {"_index": self.index_name, "_id": chunk.chunk_id}},
                    {
                        "doc": {
                            "chunk_id": chunk.chunk_id,
                            "document_id": chunk.document_id,
                            "title": chunk.title,
                            "content": chunk.content,
                            "source_uri": chunk.source_uri,
                            "allowed_roles": list(chunk.allowed_roles),
                            "embedding_model_id": chunk.embedding_model_id,
                            "embedding": list(chunk.embedding),
                        },
                        "doc_as_upsert": True,
                    },
                ]
            )
        response = self.client.bulk(body=body)
        if bool(response.get("errors")):
            raise RuntimeError("OpenSearch vector upsert returned an error")

    def search(
        self,
        vector: Sequence[float],
        top_k: int,
        allowed_roles: frozenset[str],
    ) -> Iterable[tuple[ChunkRecord, float]]:
        self.embedding_provider.config.validate(list(vector))
        response = self.client.search(
            index=self.index_name,
            body={
                "size": top_k,
                "query": {
                    "bool": {
                        "filter": [{"terms": {"allowed_roles": sorted(allowed_roles)}}],
                        "must": [{"knn": {"embedding": {"vector": list(vector), "k": top_k}}}],
                    }
                },
            },
        )
        hits = response.get("hits", {}).get("hits", [])
        records: list[tuple[ChunkRecord, float]] = []
        for hit in hits:
            source = hit.get("_source", {})
            records.append(
                (
                    ChunkRecord(
                        chunk_id=str(source["chunk_id"]),
                        document_id=str(source["document_id"]),
                        title=str(source["title"]),
                        content=str(source["content"]),
                        source_uri=str(source["source_uri"]),
                        allowed_roles=tuple(str(role) for role in source["allowed_roles"]),
                        embedding_model_id=str(source["embedding_model_id"]),
                        embedding=tuple(float(value) for value in source["embedding"]),
                    ),
                    float(hit.get("_score", 0.0)),
                )
            )
        return records


@dataclass(slots=True)
class AnalyticsService:
    """One approved latest-versus-previous calculation through Databricks."""

    executor: AnalyticsExecutor

    def compare_periods(self, request: AnalyticsRequest) -> AnalyticsResponse:
        if request.metric_name != APPROVED_ANALYTICS_METRIC:
            return self._error(request, "metric is not in the approved analytics allowlist")
        rows = [dict(row) for row in self.executor.read_metric_rows(request.metric_name)]
        if not rows:
            return self._error(request, "approved analytics source returned no rows")
        periods = sorted({str(row["metric_date"]) for row in rows})
        if len(periods) < 2:
            return self._error(request, "at least two periods are required")
        previous_period, latest_period = periods[-2:]
        by_period = {
            period: sum(
                float(row["metric_total"]) for row in rows if str(row["metric_date"]) == period
            )
            for period in (previous_period, latest_period)
        }
        previous = by_period[previous_period]
        latest = by_period[latest_period]
        difference = latest - previous
        percentage = None if previous == 0 else difference / previous * 100
        contributor_changes: dict[str, float] = {}
        categories = {str(row["category"]) for row in rows}
        for category in categories:
            latest_value = sum(
                float(row["metric_total"])
                for row in rows
                if str(row["metric_date"]) == latest_period and str(row["category"]) == category
            )
            previous_value = sum(
                float(row["metric_total"])
                for row in rows
                if str(row["metric_date"]) == previous_period and str(row["category"]) == category
            )
            contributor_changes[category] = latest_value - previous_value
        contributor, contributor_change = min(
            contributor_changes.items(), key=lambda item: (item[1], item[0])
        )
        provenance = Provenance(
            "databricks-unity-catalog",
            "ask_david_development.green_sm_business.goal5_structured_business_metrics",
            str(uuid.uuid4()),
            freshness=latest_period,
        )
        return AnalyticsResponse(
            "success",
            latest_period,
            previous_period,
            latest,
            previous,
            difference,
            percentage,
            contributor,
            contributor_change,
            provenance,
        )

    @staticmethod
    def _error(request: AnalyticsRequest, error: str) -> AnalyticsResponse:
        return AnalyticsResponse(
            "error",
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            Provenance("databricks-unity-catalog", request.metric_name, "error"),
            error,
        )


@dataclass(frozen=True, slots=True)
class DatasetMetadata:
    dataset_name: str
    description: str
    freshness: str


@dataclass(slots=True)
class MetadataService:
    """Minimal approved metadata lookup; not a second catalog authority."""

    datasets: Mapping[str, DatasetMetadata]

    def describe(self, dataset_name: str) -> DatasetMetadata:
        try:
            return self.datasets[dataset_name]
        except KeyError as error:
            raise KeyError(f"dataset is not approved: {dataset_name}") from error


class InMemoryDorisExecutor:
    """Offline adapter that records generated SELECT statements."""

    def __init__(self, rows: Iterable[Mapping[str, Any]]) -> None:
        self.rows = tuple(dict(row) for row in rows)
        self.statements: list[str] = []

    def execute(self, sql: str) -> Iterable[Mapping[str, Any]]:
        self.statements.append(sql)
        return self.rows


class InMemoryAnalyticsExecutor:
    """Offline adapter representing a Databricks approved operation."""

    def __init__(self, rows: Iterable[Mapping[str, Any]]) -> None:
        self.rows = tuple(dict(row) for row in rows)

    def read_metric_rows(self, metric_name: str) -> Iterable[Mapping[str, Any]]:
        del metric_name
        return self.rows


class InMemoryVectorIndex:
    """Small cosine index for deterministic offline integration tests."""

    def __init__(self, embedding_provider: EmbeddingProvider) -> None:
        self.embedding_provider = embedding_provider
        self._records: dict[str, ChunkRecord] = {}

    def upsert(self, chunks: Sequence[ChunkRecord]) -> None:
        for chunk in chunks:
            if chunk.embedding_model_id != self.embedding_provider.config.model_id:
                raise ValueError("embedding model mismatch")
            self.embedding_provider.config.validate(chunk.embedding)
            self._records[chunk.chunk_id] = chunk

    def search(
        self,
        vector: Sequence[float],
        top_k: int,
        allowed_roles: frozenset[str],
    ) -> Iterable[tuple[ChunkRecord, float]]:
        self.embedding_provider.config.validate(list(vector))
        candidates = (
            chunk
            for chunk in self._records.values()
            if allowed_roles.intersection(chunk.allowed_roles)
        )
        scored = [(chunk, self._cosine(vector, chunk.embedding)) for chunk in candidates]
        return sorted(scored, key=lambda item: (-item[1], item[0].chunk_id))[:top_k]

    @staticmethod
    def _cosine(left: Sequence[float], right: Sequence[float]) -> float:
        numerator = sum(a * b for a, b in zip(left, right, strict=True))
        left_norm = sum(value * value for value in left) ** 0.5
        right_norm = sum(value * value for value in right) ** 0.5
        return 0.0 if left_norm == 0 or right_norm == 0 else numerator / (left_norm * right_norm)


def deterministic_chunk_id(document_id: str, content: str, ordinal: int) -> str:
    """Return a stable upsert key for a normalized chunk."""

    digest = hashlib.sha256(f"{document_id}\0{ordinal}\0{content}".encode()).hexdigest()
    return f"chunk-{digest}"


def parse_iso_date(value: str) -> date:
    """Validate date input used by adapters without accepting arbitrary SQL."""

    if not _DATE_RE.fullmatch(value):
        raise ValueError("date must use YYYY-MM-DD")
    return date.fromisoformat(value)
